package dev.ethanyap.slotted.booking.domain;

import dev.ethanyap.slotted.common.ApiException;
import dev.ethanyap.slotted.common.ErrorCode;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneId;
import java.time.temporal.ChronoUnit;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.UUID;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

/**
 * One booking of a room for {@code [startAt, endAt)}. The {@code slot} range column is generated by
 * the database from these two instants, so it is not mapped here (ADR-0001).
 */
@Entity
@Table(name = "booking")
public class Booking {

  /** Bookings start and end on these boundaries (BR-1). */
  private static final int BOUNDARY_MINUTES = 30;

  /** A waitlist request names only a slot, so promoted bookings are for one person. */
  public static final int PROMOTED_ATTENDEES = 1;

  @Id
  @GeneratedValue(strategy = GenerationType.UUID)
  private UUID id;

  private UUID roomId;
  private UUID userId;
  private UUID seriesId;
  private Instant startAt;
  private Instant endAt;

  @Enumerated(EnumType.STRING)
  private BookingStatus status;

  @Enumerated(EnumType.STRING)
  private BookingSource source;

  private short attendees;
  private String purpose;
  private Instant checkedInAt;
  private Instant releasedAt;
  private Instant cancelledAt;
  private UUID cancelledBy;
  private String cancelReason;
  private boolean lateCancellation;

  @CreationTimestamp private Instant createdAt;
  @UpdateTimestamp private Instant updatedAt;
  @Version private long version;

  protected Booking() {}

  public Booking(
      UUID roomId, UUID userId, Instant startAt, Instant endAt, int attendees, String purpose) {
    this.roomId = roomId;
    this.userId = userId;
    this.startAt = startAt;
    this.endAt = endAt;
    this.attendees = (short) attendees;
    this.purpose = purpose == null || purpose.isBlank() ? null : purpose.strip();
    this.status = BookingStatus.CONFIRMED;
    this.source = BookingSource.DIRECT;
  }

  /** One date of a recurring booking. */
  public static Booking occurrence(
      UUID seriesId,
      UUID roomId,
      UUID userId,
      Instant startAt,
      Instant endAt,
      int attendees,
      String purpose) {
    var booking = new Booking(roomId, userId, startAt, endAt, attendees, purpose);
    booking.seriesId = seriesId;
    booking.source = BookingSource.SERIES;
    return booking;
  }

  /** A booking made by promoting a waitlist entry (BR-26). */
  public static Booking promoted(UUID roomId, UUID userId, Instant startAt, Instant endAt) {
    var booking = new Booking(roomId, userId, startAt, endAt, PROMOTED_ATTENDEES, null);
    booking.source = BookingSource.WAITLIST;
    return booking;
  }

  /** Status at {@code now}, derived from stored facts (ADR-0004). */
  public EffectiveStatus effectiveStatus(Instant now, BookingPolicy policy) {
    return switch (status) {
      case CANCELLED -> EffectiveStatus.CANCELLED;
      case NO_SHOW -> EffectiveStatus.NO_SHOW;
      case CHECKED_IN ->
          now.isBefore(endAt) ? EffectiveStatus.CHECKED_IN : EffectiveStatus.COMPLETED;
      case CONFIRMED -> {
        if (!now.isBefore(noShowAt(policy))) {
          yield EffectiveStatus.NO_SHOW;
        }
        yield now.isBefore(endAt) ? EffectiveStatus.CONFIRMED : EffectiveStatus.COMPLETED;
      }
    };
  }

  /** When an unchecked booking becomes a no-show and its room is released (BR-17). */
  public Instant noShowAt(BookingPolicy policy) {
    return startAt.plus(policy.noShowGrace());
  }

  public Instant checkInOpensAt(BookingPolicy policy) {
    return startAt.minus(policy.checkInOpensBefore());
  }

  /**
   * The owner cancels (BR-12, BR-13): only before the start, and within the late-cancellation
   * period it is recorded as late.
   */
  public void cancelByOwner(Instant now, BookingPolicy policy, String reason) {
    var effective = effectiveStatus(now, policy);
    if (!effective.blocksRoom()) {
      throw notCancellable(effective);
    }
    if (!now.isBefore(startAt)) {
      throw new ApiException(
          ErrorCode.ALREADY_STARTED,
          "This booking has already started, so it can no longer be cancelled."
              + " If you have checked in, you can end it early instead.");
    }
    lateCancellation = Duration.between(now, startAt).compareTo(policy.lateCancellation()) < 0;
    markCancelled(now, userId, reason);
  }

  /**
   * A manager of the facility or an admin cancels someone else's booking, at any time while it is
   * active, and must say why (BR-14).
   */
  public void cancelByStaff(UUID staffId, Instant now, BookingPolicy policy, String reason) {
    var effective = effectiveStatus(now, policy);
    if (!effective.blocksRoom()) {
      throw notCancellable(effective);
    }
    if (reason == null || reason.isBlank()) {
      throw new ApiException(
          ErrorCode.REASON_REQUIRED, "Give a reason; it is sent to the person who booked.");
    }
    markCancelled(now, staffId, reason);
  }

  /** Whether {@code now} is inside the check-in window of a confirmed booking (BR-16). */
  public boolean isCheckInOpen(Instant now, BookingPolicy policy) {
    return status == BookingStatus.CONFIRMED
        && !now.isBefore(checkInOpensAt(policy))
        && now.isBefore(noShowAt(policy));
  }

  /**
   * Checks in (BR-16). From the no-show time on, the booking has been released, so this fails even
   * if nothing has written the no-show down yet (ADR-0004). Checking in again does nothing.
   */
  public void checkIn(Instant now, BookingPolicy policy) {
    if (status == BookingStatus.CHECKED_IN) {
      return;
    }
    if (status != BookingStatus.CONFIRMED) {
      throw new ApiException(
          ErrorCode.NO_BOOKING_TO_CHECK_IN, "This booking cannot be checked in.");
    }
    if (now.isBefore(checkInOpensAt(policy))) {
      throw new ApiException(ErrorCode.CHECK_IN_NOT_OPEN, "Check-in is not open yet.");
    }
    if (!now.isBefore(noShowAt(policy))) {
      throw new ApiException(
          ErrorCode.CHECK_IN_CLOSED, "Check-in has closed, so this booking was released.");
    }
    status = BookingStatus.CHECKED_IN;
    // The database keeps microseconds; storing exactly that keeps every read the same.
    checkedInAt = now.truncatedTo(ChronoUnit.MICROS);
  }

  /**
   * Ends a checked-in booking early (BR-15): the rest is released from the next 30-minute boundary
   * in the facility's zone. A booking always keeps its first 30 minutes, so one ended before it
   * starts (check-in opens 10 minutes early) does not end before its own start.
   */
  public void endEarly(Instant now, BookingPolicy policy, ZoneId zone) {
    if (effectiveStatus(now, policy) != EffectiveStatus.CHECKED_IN) {
      throw new ApiException(
          ErrorCode.NOT_CHECKED_IN,
          "Only a booking you have checked in to, and that has not ended, can be ended early.");
    }
    if (releasedAt != null) {
      throw new ApiException(ErrorCode.NOT_CHECKED_IN, "This booking has already been ended.");
    }
    var boundary = nextBoundary(now, zone);
    var earliest = startAt.plus(Duration.ofMinutes(BOUNDARY_MINUTES));
    var newEnd = boundary.isBefore(earliest) ? earliest : boundary;
    if (newEnd.isBefore(endAt)) {
      endAt = newEnd;
    }
    releasedAt = now.truncatedTo(ChronoUnit.MICROS);
  }

  /** {@code now} if it is on a 30-minute boundary, otherwise the next one. */
  private static Instant nextBoundary(Instant now, ZoneId zone) {
    var local = now.atZone(zone).truncatedTo(ChronoUnit.MINUTES);
    var minutes = local.getMinute() % BOUNDARY_MINUTES;
    var onBoundary = minutes == 0 && local.toInstant().equals(now);
    if (onBoundary) {
      return now;
    }
    return local.minusMinutes(minutes).plusMinutes(BOUNDARY_MINUTES).toInstant();
  }

  /** The system cancels an active booking, for example when the account is disabled. */
  public void cancelBySystem(Instant now, BookingPolicy policy, String reason) {
    var effective = effectiveStatus(now, policy);
    if (!effective.blocksRoom()) {
      throw notCancellable(effective);
    }
    markCancelled(now, null, reason);
  }

  private void markCancelled(Instant now, UUID by, String reason) {
    status = BookingStatus.CANCELLED;
    cancelledAt = now;
    cancelledBy = by;
    cancelReason = reason == null || reason.isBlank() ? null : reason.strip();
  }

  private static ApiException notCancellable(EffectiveStatus effective) {
    var what =
        switch (effective) {
          case CANCELLED -> "already cancelled";
          case NO_SHOW -> "a no-show and its room has been released";
          default -> "already over";
        };
    return new ApiException(ErrorCode.NOT_CANCELLABLE, "This booking is " + what + ".");
  }

  /** The values the audit log keeps for a booking (BR-32). */
  public Map<String, Object> auditState() {
    var state = new LinkedHashMap<String, Object>();
    state.put("roomId", roomId);
    state.put("userId", userId);
    state.put("seriesId", seriesId);
    state.put("startAt", startAt);
    state.put("endAt", endAt);
    state.put("status", status);
    state.put("source", source);
    state.put("attendees", (int) attendees);
    state.put("purpose", purpose);
    state.put("checkedInAt", checkedInAt);
    state.put("releasedAt", releasedAt);
    state.put("cancelledAt", cancelledAt);
    state.put("cancelledBy", cancelledBy);
    state.put("cancelReason", cancelReason);
    state.put("lateCancellation", lateCancellation);
    return state;
  }

  public UUID getId() {
    return id;
  }

  public UUID getRoomId() {
    return roomId;
  }

  public UUID getUserId() {
    return userId;
  }

  public UUID getSeriesId() {
    return seriesId;
  }

  public Instant getStartAt() {
    return startAt;
  }

  public Instant getEndAt() {
    return endAt;
  }

  public BookingStatus getStatus() {
    return status;
  }

  public BookingSource getSource() {
    return source;
  }

  public int getAttendees() {
    return attendees;
  }

  public String getPurpose() {
    return purpose;
  }

  public Instant getCheckedInAt() {
    return checkedInAt;
  }

  public Instant getReleasedAt() {
    return releasedAt;
  }

  public Instant getCancelledAt() {
    return cancelledAt;
  }

  public String getCancelReason() {
    return cancelReason;
  }

  public boolean isLateCancellation() {
    return lateCancellation;
  }

  public Instant getCreatedAt() {
    return createdAt;
  }
}
